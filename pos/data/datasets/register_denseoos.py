def _get_denseoos_cityscapes_meta():
    stuff_classes = [
        "road",
        "sidewalk",
        "building",
        "wall",
        "fence",
        "pole",
        "traffic light",
        "traffic sign",
        "vegetation",
        "terrain",
        "sky",
        "person",
        "rider",
        "car",
        "truck",
        "bus",
        "train",
        "motorcycle",
        "bicycle",
    ]
    assert len(stuff_classes) == 19, f"Given: {len(stuff_classes)}"

    ret = {
        "stuff_classes": stuff_classes,
    }
    return ret

_RAW_DENSEOOS_SPLITS = {
    "denseoos_cityscapes_{task}_val": ("DenseOoS/leftImg8bit/val/", "DenseOoS/gtFine/val/"),
    }

ignore_label = list(range(19, 49)) + [255]

def register_denseoos_cityscapes(root):
    for key, (image_dir, gt_dir) in _RAW_DENSEOOS_SPLITS.items():
        meta = _get_denseoos_cityscapes_meta()
        image_dir = os.path.join(root, image_dir)
        gt_dir = os.path.join(root, gt_dir)

        sem_key = key.format(task="sem_seg")
        DatasetCatalog.register(
                sem_key, lambda x=image_dir, y=gt_dir: load_sem_seg(y, x, gt_ext="png", image_ext="png")
        )
        MetadataCatalog.get(sem_key).set(
            image_dir=image_dir,
            gt_dir=gt_dir,
            evaluator_type="sem_seg_panoramic",
            ignore_label=ignore_label,  # the ignore label for denseoos: 19-48 and 255
            **meta,
        )

_root = os.getenv("DETECTRON2_DATASETS", "datasets")
register_denseoos_cityscapes(_root)